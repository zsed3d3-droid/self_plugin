import {makeScene2D} from '@motion-canvas/2d/lib/scenes';
import {Rect,Txt,Line} from '@motion-canvas/2d/lib/components';
import {all,waitFor} from '@motion-canvas/core';
export const labels: Array<{name:string,node:Txt}>=[];
export default makeScene2D(function*(view){
 labels.length=0;
 const text=(parent:any,name:string,content:string,props:any={})=>{const wide=['title','subtitle','final-caption','illustration-note'].includes(name);const node=new Txt({text:content,width:wide?1120:300,height:name==='title'?64:40,textWrap:false,textAlign:'center',fontFamily:'Arial, sans-serif',fontSize:22,fill:'#353c40',...props});parent.add(node);labels.push({name,node});return node;};
 text(view,'title','Originals stay. Names change.',{y:-265,fontSize:48,fontWeight:700});
 text(view,'subtitle','Follow one file from its original name to a reviewed copy.',{y:-205,fontSize:23,fill:'#5b6267'});
 const cards=[-400,0,400].map(x=>{const node=new Rect({x,y:20,width:330,height:270,radius:18,fill:'#ffffff',stroke:'#bfc6c7',lineWidth:2});view.add(node);return node;});
 ['01  ORIGINAL','02  REVIEW','03  COPY BUNDLE'].forEach((name,i)=>text(cards[i],`heading-${i}`,name,{y:-86,fontSize:19,fontWeight:700,fill:'#566469'}));
 text(cards[0],'original-name','raw?.txt',{y:-23,fontSize:30});
 text(cards[0],'original-caption','Original bytes retained',{y:57,fontSize:20});
 text(cards[1],'reviewed-name','reviewed.txt',{y:-23,fontSize:30});
 text(cards[1],'review-caption','A name you checked',{y:57,fontSize:20});
 text(cards[2],'bundle-name','delivery.zip',{y:-23,fontSize:30});
 text(cards[2],'bundle-caption','A renamed copy + mapping',{y:57,fontSize:20});
 const first=new Line({points:[[-227,20],[-173,20]],stroke:'#1d7562',lineWidth:4,endArrow:true,arrowSize:11,end:0});
 const second=new Line({points:[[173,20],[227,20]],stroke:'#1d7562',lineWidth:4,endArrow:true,arrowSize:11,end:0});view.add(first);view.add(second);
 const final=text(view,'final-caption','Reviewed names travel with copies. Originals are unchanged.',{y:235,fontSize:24,fontWeight:700,fill:'#225e50',opacity:0});
 text(view,'illustration-note','ILLUSTRATION ONLY · No uploads or file operations in this lab',{y:298,fontSize:17,fill:'#5b6267'});
 cards[0].fill('#fff1c9');cards[0].stroke('#a46e17');
 yield* waitFor(1.2);
 yield* all(first.end(1,1.2),cards[1].fill('#edf5ff',1.2),cards[1].stroke('#467492',1.2));
 yield* waitFor(1.6);
 yield* all(second.end(1,1.2),cards[2].fill('#e2f3e8',1.2),cards[2].stroke('#1d7562',1.2));
 yield* waitFor(2.5);
 yield* final.opacity(1,.4);
 yield* waitFor(1.9);
});
